#!/usr/bin/env python3
"""Generate distribution metadata from VERSION; --check rejects drift."""
import argparse
import json
from pathlib import Path
import re
import sys

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
version = (root / "VERSION").read_text().strip()
if not re.fullmatch(r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?", version):
    sys.exit("VERSION must contain SemVer without a leading v")
module = (root / "go.mod").read_text().splitlines()[0].split()[1]
project = module.rsplit("/", 1)[1]
outputs = {}

def stamp_json(path):
    data = json.loads(path.read_text())
    data["version"] = version
    for name in data.get("optionalDependencies", {}):
        if name.startswith("@graycodeai/decoder-"):
            data["optionalDependencies"][name] = version
    indent = 4 if project == "decoder" else 2
    outputs[path] = json.dumps(data, indent=indent) + "\n"

for path in sorted((root / "npm").glob("*/package.json")):
    stamp_json(path)
if project == "mux":
    stamp_json(root / "internal/sdk/typescript/package.json")
    path = root / "internal/sdk/python/pyproject.toml"
    outputs[path] = re.sub(r'^version = ".*"$', 'version = "' + version + '"', path.read_text(), count=1, flags=re.M)
    outputs[root / "internal/buildversion/version.go"] = (
        "// Code generated by scripts/sync-version.py from VERSION; DO NOT EDIT.\n"
        "package buildversion\n\n"
        '// Version is the canonical project version for lower provider layers.\n'
        'const Version = "' + version + '"\n'
    )
path = root / "api/openapi.yaml"
outputs[path] = re.sub(r'^  version: .*$', '  version: "' + version + '"', path.read_text(), count=1, flags=re.M)
stale = []
for path, content in outputs.items():
    if not path.exists() or path.read_text() != content:
        stale.append(str(path.relative_to(root)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
if args.check and stale:
    sys.exit("Stale metadata: " + ", ".join(stale) + "; run make version-sync")
print(project + ": metadata matches VERSION " + version)
